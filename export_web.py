"""Export both brains and all trained readouts to web/brains.js for the browser version.

    python export_web.py

The wiring is stored sparse (CSR) and float32, base64-encoded. Input weights are
stored only for sensory neurons (all other rows are zero by construction).
Also writes web/test_vectors.js so the JS engine can be checked against Python.
"""
import base64
import json
import os
import numpy as np
import brain as br
from train import load_or_train, SIZES

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "web")


def b64(a, dtype):
    return base64.b64encode(np.ascontiguousarray(a, dtype=dtype).tobytes()).decode()


def export():
    data = {"leak": br.LEAK, "steps": br.STEPS, "brains": {}}
    tests = {}
    rng = np.random.default_rng(3)
    for key in ("worm", "fly"):
        wr = br.get_wiring(key)
        W = wr.W
        rows, cols = np.nonzero(W)
        indptr = np.searchsorted(rows, np.arange(wr.N + 1))
        sens = np.where(wr.sensory)[0]
        entry = {
            "label": wr.label, "n": wr.N, "info": wr.info,
            "indptr": b64(indptr, np.int32), "indices": b64(cols, np.int32),
            "weights": b64(W[rows, cols], np.float32),
            "sensory": sens.tolist(), "readout": np.where(wr.readout)[0].tolist(),
            "order": wr.order.tolist(), "games": {},
        }
        for game, (n_in, n_out) in SIZES.items():
            m = load_or_train(key, game)
            entry["games"][game] = {
                "nIn": n_in, "nOut": n_out,
                "B": b64(m.B[sens], np.float32),  # (n_sensory, n_in)
                "bias": b64(m.bias, np.float32),
                "Wout": b64(m.Wout, np.float32),  # (n_out, n_readout + 1)
            }
            X = rng.random((3, n_in))
            tests[f"{key}_{game}"] = {"x": X.tolist(), "y": m.predict(X).tolist()}
        data["brains"][key] = entry
        print(key, "nnz", len(cols))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "brains.js"), "w", encoding="utf-8") as f:
        f.write("// generated by export_web.py - real connectome wiring + trained readouts\n"
                "// fly wiring: derived from FlyWire public release 783 (Dorkenwald et al. 2024,\n"
                "//   Schlegel et al. 2024), licensed CC BY-NC 4.0 - non-commercial use only.\n"
                "//   https://creativecommons.org/licenses/by-nc/4.0/\n"
                "// worm wiring: derived from Cook et al. 2019 via OpenWorm cect (MIT).\n"
                "// See README.md for what was changed and the full citations.\n")
        f.write("window.BRAIN_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
    with open(os.path.join(OUT, "test_vectors.js"), "w", encoding="utf-8") as f:
        f.write("module.exports = " + json.dumps(tests) + ";\n")
    print("size MB", round(os.path.getsize(os.path.join(OUT, "brains.js")) / 1e6, 2))


if __name__ == "__main__":
    export()
    import ai
    if ai.load() is not None:
        print("my AI ->", ai.export_js())
