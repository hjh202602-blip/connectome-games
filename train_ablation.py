"""Score-rule experiment: the same trained AI, trained 8 times from scratch, once for every
on/off combination of the three bonuses (return, spin, aiming far from the opponent).

    python train_ablation.py          # train all 8 at once (8 processes), test, write web/ablation.js
    python train_ablation.py eval     # only test the saved ones and write web/ablation.js

Everything else is identical for the 8 runs: the same starting network, the same random
noise, the same opponents as v1 (4x predictor, 2x straight-line guesser, 2x itself) and the
same number of generations. Points always count; only the bonuses are switched.
"""
import os
import sys
import time
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")  # one core per process
import json
import multiprocessing as mp
import numpy as np
import ai
import train_ai as T

BONUS = (("return", "받아치기", 0.02), ("spin", "회전", 0.04), ("far", "먼 쪽", 0.06))
COMBOS = [(r, s, f) for r in (1, 0) for s in (1, 0) for f in (1, 0)]
GENS, POP = 250, 64
GAMES = [T.PRED] * 4 + [T.LINE] * 2 + [T.SELF] * 2
DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models", "ablation")
EVAL_N = 64                       # rallies of 60 s per test match
EVAL_OPP = ("worm", "fly", "pred")


def key(c):
    return "".join(map(str, c))


def path(c):
    return os.path.join(DIR, f"combo_{key(c)}.npz")


def train(c):
    """Train one combination from scratch. Runs in its own process."""
    T.RETURN_BONUS, T.SPIN_BONUS, T.FAR_BONUS = (on * b[2] for on, b in zip(c, BONUS))
    rng = np.random.default_rng(0)            # same start and same noise for every combination
    theta = ai.init(rng)
    m, v = np.zeros_like(theta), np.zeros_like(theta)
    hist = {k: [] for k in ("pred", "line", "hits", "spin", "far")}
    half, t0 = POP // 2, time.time()
    for gen in range(1, GENS + 1):
        eps = rng.normal(0, 1, (half, ai.N_PARAMS))
        eps = np.concatenate([eps, -eps])
        score, points, hits, spin, far, kind = T.play(theta + T.SIGMA * eps, {T.SELF: theta}, GAMES,
                                                       int(rng.integers(2 ** 31)), {})
        ranks = np.empty(POP)
        ranks[np.argsort(score.mean(1))] = np.arange(POP)
        grad = (ranks / (POP - 1) - 0.5) @ eps / (POP * T.SIGMA)
        m = 0.9 * m + 0.1 * grad
        v = 0.999 * v + 0.001 * grad ** 2
        theta = theta + T.LR * (m / (1 - 0.9 ** gen)) / (np.sqrt(v / (1 - 0.999 ** gen)) + 1e-8)
        n = max(hits.sum(), 1)
        hist["pred"].append(points[:, kind[0] == T.PRED].mean())
        hist["line"].append(points[:, kind[0] == T.LINE].mean())
        hist["hits"].append(hits.mean())
        hist["spin"].append(spin.sum() / n)
        hist["far"].append(far.sum() / n)
        if gen % 10 == 0 or gen == GENS:
            os.makedirs(DIR, exist_ok=True)
            meta = {"gens": gen, "games": gen * POP * len(GAMES), "combo": key(c), "hist": hist}
            np.savez(path(c), theta=theta, meta=np.array(meta, dtype=object))
        if gen % 25 == 0:
            print(f"[{label(c)}] {gen}세대 | 예측 {hist['pred'][-1]:+.2f} 직선 {hist['line'][-1]:+.2f} | "
                  f"받아친 공 {hist['hits'][-1]:.1f} | 회전 {hist['spin'][-1]:.0%} | 먼 쪽 {hist['far'][-1]:.0%} | "
                  f"{time.time() - t0:.0f}초", flush=True)
    return key(c)


def label(c):
    on = [b[1] for o, b in zip(c, BONUS) if o]
    return ("+".join(on) if on else "보너스 없음")


def test(job):
    import eval_ai as E
    c, opp = job
    theta = ai.load_theta(path(c))[0]
    w, l, h, s, f = E.match(theta, opp, np.random.default_rng(7), n=EVAL_N)
    return key(c), opp, int(w), int(l), int(h), float(s), float(f)


def export(results):
    data = {"gens": GENS, "pop": POP, "evalRallies": EVAL_N,
            "bonus": [{"id": b[0], "name": b[1], "size": b[2]} for b in BONUS], "combos": {}}
    for c in COMBOS:
        theta, meta = ai.load_theta(path(c))
        data["combos"][key(c)] = {
            "nIn": ai.N_IN, "hidden": ai.HID, "gens": meta["gens"], "games": meta["games"],
            "theta": [round(float(x), 6) for x in theta],
            "hist": {k: [round(float(x), 4) for x in v] for k, v in meta["hist"].items()},
            "eval": results.get(key(c), {})}
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "web", "ablation.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// generated by train_ablation.py - the score-rule experiment (8 AIs, see README)\n")
        f.write("window.ABL_DATA = " + json.dumps(data, ensure_ascii=False) + ";\n")
    return out


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    workers = max(1, min(8, (os.cpu_count() or 2)))
    if "eval" not in sys.argv:
        print(f"8가지 조합을 처음부터 {GENS}세대씩 학습합니다 (프로세스 {workers}개).", flush=True)
        with mp.Pool(workers) as pool:
            for k in pool.imap_unordered(train, COMBOS):
                print("끝:", label(tuple(map(int, k))), flush=True)
    print("시험 경기를 합니다...", flush=True)
    results = {}
    jobs = [(c, o) for c in COMBOS for o in EVAL_OPP]
    with mp.Pool(workers) as pool:
        for k, o, w, l, h, s, f in pool.imap_unordered(test, jobs):
            r = results.setdefault(k, {})
            r[o] = [w, l]
            r.setdefault("hits", []).append(h)
            r.setdefault("spin", []).append(s)
            r.setdefault("far", []).append(f)
            print(f"[{label(tuple(map(int, k)))}] vs {o}: {w}:{l}", flush=True)
    for r in results.values():  # averages over the three test opponents
        r["hits"] = round(sum(r["hits"]) / len(r["hits"]) / EVAL_N, 2)  # returns per 60 s rally
        r["spin"] = round(sum(r["spin"]) / len(r["spin"]), 3)
        r["far"] = round(sum(r["far"]) / len(r["far"]), 3)
    print("웹 버전에 넣었습니다:", export(results))


if __name__ == "__main__":
    main()
