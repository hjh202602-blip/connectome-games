"""'My AI': a small ordinary neural network (not a connectome) that plays paddle ball.
It is trained in train_ai.py and saved to models/ai_paddle.npz (v1) and
models/ai_paddle_v2.npz (v2, which also practised against the insect brains).

Network: 10 inputs -> 32 tanh -> 32 tanh -> 1 tanh (paddle move, -1..1).
Unlike the insect brains it also sees the spin, its own last move and the opponent,
so it can learn to read curving balls and to brush the ball to put spin on it.
It moves its paddle exactly like the human does (same push, friction and top speed,
paddle.move_inertia), so it also sees its own paddle speed.
"""
import os
import numpy as np
import paddle as pd

N_IN, HID = 10, 32
SHAPES = [("W1", (N_IN, HID)), ("b1", (HID,)), ("W2", (HID, HID)), ("b2", (HID,)), ("W3", (HID,)), ("b3", ())]
N_PARAMS = sum(int(np.prod(s)) for _, s in SHAPES)
PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models", "ai_paddle.npz")


def features(ball, side, me, opp, prev, vel):
    """Inputs for the player on `side`, seen as if it sits at x = 0.97."""
    bx, by, vx, vy, spin = pd.view(ball, side)
    vel = np.broadcast_to(vel, np.shape(bx))
    return np.stack([bx * 2 - 1, by * 2 - 1, vx * 40, vy * 40, spin / pd.SPIN_MAX,
                     me * 2 - 1, (by - me) * 2, opp * 2 - 1, np.broadcast_to(prev, np.shape(bx)), vel * 50], -1)


def load_theta(p):
    """Weights from a saved file. Files from before the paddle had inertia have 9 inputs;
    the missing 'own paddle speed' input is added with zero weights."""
    d = np.load(p, allow_pickle=True)
    theta = d["theta"].astype(float)
    if theta.size == N_PARAMS - HID:
        theta = np.insert(theta, (N_IN - 1) * HID, np.zeros(HID))
    return theta, (d["meta"].item() if "meta" in d else {})


def unpack(theta):
    """theta (..., N_PARAMS) -> dict of weights with the same leading dims."""
    out, k = {}, 0
    lead = theta.shape[:-1]
    for name, s in SHAPES:
        n = int(np.prod(s))
        out[name] = theta[..., k:k + n].reshape(lead + s)
        k += n
    return out


def forward(theta, X):
    """theta (P, N_PARAMS), X (P, G, N_IN) -> outputs (P, G), hidden layers."""
    w = unpack(theta)
    h1 = np.tanh(X @ w["W1"] + w["b1"][:, None])
    h2 = np.tanh(h1 @ w["W2"] + w["b2"][:, None])
    out = np.tanh((h2 @ w["W3"][..., None])[..., 0] + w["b3"][:, None])
    return out, h1, h2


def init(rng):
    w = {"W1": rng.normal(0, 1 / np.sqrt(N_IN), (N_IN, HID)), "b1": np.zeros(HID),
         "W2": rng.normal(0, 1 / np.sqrt(HID), (HID, HID)), "b2": np.zeros(HID),
         "W3": rng.normal(0, 0.1 / np.sqrt(HID), HID), "b3": np.zeros(())}
    return np.concatenate([np.ravel(w[n]) for n, _ in SHAPES])


class _Info:
    """Looks enough like a brain's wiring for the side panel's neuron grid."""
    N = 2 * HID
    order = np.arange(2 * HID)

    def __init__(self, ver, meta):
        self.label = f"학습 AI {ver}"
        how = "스스로 연습" if ver == "v1" else "v1에서 곤충 뇌와 겨루며 연습"
        self.info = ["일반 신경망 10 → 32 → 32 → 1 (커넥톰 아님)",
                     f"{how} · 모두 {meta.get('gens', 0)}세대, 경기 {meta.get('games', 0):,}판",
                     "사람과 같은 관성으로 움직임 · 회전·상대 위치까지 봄"]


class PaddleAI:
    """Game-side wrapper. move() decides and moves the paddle with human-like inertia."""

    def __init__(self, ver="v1"):
        self.theta, meta = load_theta(path(ver))
        self.wiring = _Info(ver, meta)
        self.last_state = np.zeros(2 * HID)
        self.prev = 0.0
        self.vel = 0.0

    def move(self, ball, side, me, opp):
        """Returns the paddle's new position."""
        x = features(np.asarray(ball, float), side, me, opp, self.prev, self.vel)
        out, h1, h2 = forward(self.theta[None], x.reshape(1, 1, N_IN))
        self.last_state = np.concatenate([h1[0, 0], h2[0, 0]])
        self.prev = float(out[0, 0])
        new, vel, _ = pd.move_inertia(me, self.vel, self.prev)
        self.vel = float(vel)
        return float(new)


def path(ver="v1"):
    return PATH if ver == "v1" else PATH.replace(".npz", f"_{ver}.npz")


def export_js():
    """Write every saved AI version to web/ai.js so the browser version plays them too."""
    import json
    data = {}
    for ver in VERSIONS:
        if not os.path.exists(path(ver)):
            continue
        theta, meta = load_theta(path(ver))
        data[ver] = {"nIn": N_IN, "hidden": HID, "gens": meta["gens"], "games": meta["games"],
                     "theta": [round(float(v), 6) for v in theta]}
    out = os.path.join(os.path.dirname(PATH), "..", "web", "ai.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// generated by train_ai.py / export_web.py - trained AI for paddle ball (see ai.py)\n")
        f.write("window.AI_DATA = " + json.dumps(data) + ";\n")
    return os.path.abspath(out)


VERSIONS = ("v1", "v2")


def load(ver="v1"):
    return PaddleAI(ver) if os.path.exists(path(ver)) else None
